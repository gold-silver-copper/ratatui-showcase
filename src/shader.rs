//! The WGSL program: constants generated from the Rust side, then its
//! modules joined in order, checked with naga (the compiler wgpu uses), and,
//! with `--watch`, re-read from disk when they change so effects can be tuned
//! live.

use std::fmt::Write;
use std::path::PathBuf;
use std::time::SystemTime;

use crate::art::Style;
use crate::backdrop::BACKDROPS;
use crate::params::{FROM, H, PIECE_LEN, Region, S, TO};
use crate::stage::{IDLES, Look, Mode, Post};
use crate::theme::SHADERS;
use crate::transition;

/// Every module, in the order they are joined: each may use what the ones
/// before it define.
const MODULES: &[(&str, &str)] = &[
    ("common", include_str!("shaders/common.wgsl")),
    ("theme", include_str!("shaders/theme.wgsl")),
    ("art", include_str!("shaders/art.wgsl")),
    ("jfa", include_str!("shaders/jfa.wgsl")),
    ("backdrop", include_str!("shaders/backdrop.wgsl")),
    ("three_d", include_str!("shaders/three_d.wgsl")),
    ("transitions", include_str!("shaders/transitions.wgsl")),
    ("sims", include_str!("shaders/sims.wgsl")),
    ("particles", include_str!("shaders/particles.wgsl")),
    ("scene", include_str!("shaders/scene.wgsl")),
    ("post", include_str!("shaders/post.wgsl")),
    ("encode", include_str!("shaders/encode.wgsl")),
];

/// The program as built into the binary.
pub fn built_in() -> String {
    join(MODULES.iter().map(|(_, source)| *source))
}

fn join<'a>(modules: impl Iterator<Item = &'a str>) -> String {
    let mut program = prelude();
    for module in modules {
        program.push_str(module);
        program.push('\n');
    }
    program
}

/// `"BgOld"` or `"burning ship"` as `BG_OLD` or `BURNING_SHIP`.
fn constant(name: &str) -> String {
    let mut out = String::new();
    let mut previous = ' ';
    for c in name.chars() {
        if c == ' ' || c == '-' {
            out.push('_');
        } else {
            if c.is_ascii_uppercase()
                && (previous.is_ascii_lowercase() || previous.is_ascii_digit())
            {
                out.push('_');
            }
            out.push(c.to_ascii_uppercase());
        }
        previous = c;
    }
    out
}

/// WGSL constants for the params layout (`params.rs`) and every option's
/// number, so the shaders name them instead of counting.
fn prelude() -> String {
    let mut out = String::from("// Generated by shader.rs from the Rust side.\n");
    let mut put = |prefix: &str, name: &str, value: usize| {
        let _ = writeln!(out, "const {prefix}{}: u32 = {value}u;", constant(name));
    };
    for &(slot, name, _) in H::ALL {
        put("H_", name, slot.at());
    }
    for &(region, name, _) in Region::ALL {
        put("H_", name, H::Regions.at().saturating_add(region.at()));
    }
    put("H_", "From", FROM);
    put("H_", "To", TO);
    for &(slot, name, _) in S::ALL {
        put("S_", name, slot.at());
    }
    put("", "PieceLen", PIECE_LEN);
    put(
        "",
        "Agents",
        usize::try_from(crate::gpu::AGENTS).unwrap_or(0),
    );
    put(
        "",
        "LeniaRadius",
        usize::try_from(crate::gpu::LENIA_RADIUS).unwrap_or(0),
    );
    let index = |code: u32| usize::try_from(code).unwrap_or(0);
    for (i, b) in BACKDROPS.iter().enumerate() {
        put("B_", &format!("{b:?}"), i);
    }
    put("K_", "Still", 0);
    for k in transition::ALL {
        put("K_", k.name(), index(k.code()));
    }
    for l in Look::ALL {
        put("L_", &format!("{l:?}"), index(l.code()));
    }
    for m in Mode::ALL {
        put("M_", &format!("{m:?}"), index(m.code()));
    }
    for p in Post::ALL {
        put("P_", &format!("{p:?}"), index(p.code()));
    }
    for s in Style::ALL {
        put("ST_", &format!("{s:?}"), index(s.code()));
    }
    for (i, s) in SHADERS.iter().enumerate() {
        put("SH_", &format!("{s:?}"), i);
    }
    for (i, idle) in IDLES.iter().enumerate() {
        put("I_", &format!("{idle:?}"), i);
    }
    out
}

/// A compute entry point and the pipeline constants it is built with.
pub struct Entry {
    pub name: &'static str,
    pub step: u32,
    pub flip: u32,
}

/// Checks that `source` compiles, and that each of `entries` exists and
/// still compiles once its pipeline constants are filled in. The error
/// names the line it is on.
pub fn validate(source: &str, entries: &[Entry]) -> Result<(), String> {
    let module = naga::front::wgsl::parse_str(source).map_err(|e| e.emit_to_string(source))?;
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .map_err(|e| e.emit_to_string(source))?;
    for entry in entries {
        if !module.entry_points.iter().any(|e| e.name == entry.name) {
            return Err(format!("no entry point {}", entry.name));
        }
        let constants = naga::back::PipelineConstants::from([
            ("STEP".into(), f64::from(entry.step)),
            ("FLIP".into(), f64::from(entry.flip)),
        ]);
        let stage = Some((naga::ShaderStage::Compute, entry.name));
        naga::back::pipeline_constants::process_overrides(&module, &info, stage, &constants)
            .map_err(|e| {
                format!(
                    "{} with STEP {} FLIP {}: {e}",
                    entry.name, entry.step, entry.flip
                )
            })?;
    }
    Ok(())
}

/// The modules' files in the source tree, for `--watch`.
#[derive(bevy::prelude::Resource)]
pub struct Watch {
    dir: PathBuf,
    seen: Option<SystemTime>,
}

impl Watch {
    pub fn new() -> Self {
        Self {
            dir: PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("src")
                .join("shaders"),
            seen: None,
        }
    }

    /// The program from disk, if any module changed since last asked.
    pub fn changed(&mut self) -> Option<Result<String, String>> {
        let paths = MODULES
            .iter()
            .map(|(name, _)| self.dir.join(format!("{name}.wgsl")));
        let newest = paths
            .clone()
            .filter_map(|p| p.metadata().and_then(|m| m.modified()).ok())
            .max();
        if newest.is_none() || newest == self.seen {
            return None;
        }
        let first = self.seen.is_none();
        self.seen = newest;
        if first {
            return None;
        }
        let read: Result<Vec<String>, String> = paths
            .map(|p| std::fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display())))
            .collect();
        Some(read.map(|sources| join(sources.iter().map(String::as_str))))
    }
}

